#!/usr/bin/env node
/**
 * Generates every raster icon the installable apps need from the Orbit mark:
 *   public/icons/icon-{192,512}.png       manifest "any" icons (rounded tile)
 *   public/icons/maskable-{192,512}.png   Android adaptive icons (full bleed, mark inside the 80% safe zone)
 *   public/icons/badge-96.png             monochrome status-bar badge for Android notifications
 *   public/icons/shortcut-*.png           home-screen long-press shortcuts
 *   src/app/apple-icon.png                iOS home-screen icon (full bleed; iOS applies its own mask)
 *
 * Run: node scripts/generate-icons.mjs
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = (p) => path.join(root, p);

const INK = "#1c1b19";
const PAPER = "#faf9f7";
const VERMILION = "#d4502f";

/** The Orbit mark on a 32×32 grid, optionally scaled around the centre. */
function mark(scale = 1) {
  return `<g transform="translate(16 16) scale(${scale}) translate(-16 -16)">
    <circle cx="16" cy="16" r="6.2" fill="none" stroke="${PAPER}" stroke-width="2.6"/>
    <circle cx="24.2" cy="9.6" r="3" fill="${VERMILION}" stroke="${INK}" stroke-width="1.6"/>
  </g>`;
}

const svg = (body) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">${body}</svg>`;

const ICONS = {
  rounded: svg(`<rect width="32" height="32" rx="9" fill="${INK}"/>${mark(1)}`),
  // Safe zone for maskable icons is a centred circle of radius 40%: scale 0.8 keeps the satellite dot inside it.
  maskable: svg(`<rect width="32" height="32" fill="${INK}"/>${mark(0.8)}`),
  apple: svg(`<rect width="32" height="32" fill="${INK}"/>${mark(0.9)}`),
  // Android tints badges itself: white on transparent, the gap around the dot cut out with a mask.
  badge: svg(`<defs><mask id="m"><rect width="32" height="32" fill="#fff"/><circle cx="24.2" cy="9.6" r="4.6" fill="#000"/></mask></defs>
    <g mask="url(#m)"><circle cx="15" cy="17" r="8" fill="none" stroke="#fff" stroke-width="3.4"/></g>
    <circle cx="24.2" cy="9.6" r="3.4" fill="#fff"/>`),
};

async function lucide(name) {
  const mod = await import(path.join(root, "node_modules/lucide-react/dist/esm/icons", `${name}.mjs`));
  return mod.__iconData.node.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${v}"`).join(" ")}/>`).join("");
}

async function shortcutIcon(name) {
  const glyph = await lucide(name);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 96 96">
    <rect width="96" height="96" rx="24" fill="${INK}"/>
    <g transform="translate(26 26) scale(1.8333)" fill="none" stroke="${PAPER}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${glyph}</g>
  </svg>`;
}

async function png(svgText, size, file) {
  await sharp(Buffer.from(svgText), { density: 72 * Math.ceil(size / 32) })
    .resize(size, size)
    .png({ compressionLevel: 9 })
    .toFile(out(file));
  console.log("wrote", file);
}

await mkdir(out("public/icons"), { recursive: true });
await png(ICONS.rounded, 192, "public/icons/icon-192.png");
await png(ICONS.rounded, 512, "public/icons/icon-512.png");
await png(ICONS.maskable, 192, "public/icons/maskable-192.png");
await png(ICONS.maskable, 512, "public/icons/maskable-512.png");
await png(ICONS.badge, 96, "public/icons/badge-96.png");
await png(ICONS.apple, 180, "src/app/apple-icon.png");
for (const [file, icon] of [
  ["compose", "square-pen"],
  ["search", "search"],
  ["followups", "list-checks"],
  ["unread", "mail-open"],
]) {
  await png(await shortcutIcon(icon), 96, `public/icons/shortcut-${file}.png`);
}
await writeFile(out("public/icons/README.md"), "Generated by `node scripts/generate-icons.mjs` from the Orbit mark. Don't edit by hand.\n");
